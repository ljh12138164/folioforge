import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {unzipSync} from 'fflate';

test('Rust WASM HEIC: offline conversion, comparison, downloads, restore and PNG round trip',async({page,context},testInfo)=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/convert/?format=HEIC&quality=82&maxWidth=257');
  await expect(page.locator('.app-shell')).toHaveAttribute('aria-busy','false');
  await expect(page.locator('footer')).toContainText('16 种导出格式');
  await expect(page.getByRole('button',{name:'HEIC',exact:true})).toHaveAttribute('aria-pressed','true');
  await expect(page.getByRole('checkbox',{name:/移除元数据/})).toHaveCount(0);
  await expect(page.getByLabel('透明区域填充颜色')).toBeVisible();
  await page.getByLabel('选择图片文件').setInputFiles(resolve('public/sample-landscape.png'));
  await expect(page.locator('.convert-button')).toBeEnabled();
  // Both codecs have loaded in the worker; processing and download need no network.
  await context.setOffline(true);
  await page.locator('.convert-button').click();
  await expect(page.locator('.status-done')).toHaveCount(1,{timeout:30_000});
  await expect(page.getByRole('region',{name:'图片转换前后对照'})).toBeVisible();
  await expect.poll(()=>page.locator('.image-compare-layer img').evaluateAll(images=>images.length===2&&images.every(image=>image.complete&&image.naturalWidth>0))).toBe(true);
  const downloadEvent=page.waitForEvent('download');
  await page.getByRole('button',{name:'下载 sample-landscape.heic',exact:true}).click();
  const download=await downloadEvent;
  expect(download.suggestedFilename()).toBe('sample-landscape.heic');
  const heicPath=testInfo.outputPath('result.heic');await download.saveAs(heicPath);
  const heic=await readFile(heicPath);expect(heic.subarray(4,12).toString()).toBe('ftypheic');
  const zipEvent=page.waitForEvent('download');
  await page.getByRole('button',{name:'下载 ZIP',exact:true}).click();
  const zipPath=testInfo.outputPath('results.zip');await(await zipEvent).saveAs(zipPath);
  const zip=unzipSync(await readFile(zipPath));
  expect(Buffer.from(zip['sample-landscape.heic'])).toEqual(heic);
  await page.screenshot({path:testInfo.outputPath('heic-comparison.png'),fullPage:true});
  await context.setOffline(false);
  await page.reload();
  await expect(page.locator('.app-shell')).toHaveAttribute('aria-busy','false');
  await expect(page.locator('.status-done')).toHaveCount(1);
  await expect(page.getByRole('button',{name:'下载 sample-landscape.heic',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'清空',exact:true}).click();
  await expect(page.locator('.file-row')).toHaveCount(0);
  await expect(page.locator('.app-shell')).toHaveAttribute('aria-busy','false');
  await page.getByLabel('选择图片文件').setInputFiles({name:'roundtrip.heic',mimeType:'image/heic',buffer:heic});
  await page.getByRole('button',{name:'PNG',exact:true}).click();
  await expect(page.locator('.convert-button')).toBeEnabled();await page.locator('.convert-button').click();
  await expect(page.locator('.status-done')).toHaveCount(1);
  const pngEvent=page.waitForEvent('download');
  await page.getByRole('button',{name:'下载 roundtrip.png',exact:true}).click();
  const pngPath=testInfo.outputPath('roundtrip.png');await(await pngEvent).saveAs(pngPath);
  const png=await readFile(pngPath);expect(png.subarray(1,4).toString()).toBe('PNG');expect(png.readUInt32BE(16)).toBe(257);
  expect(errors).toEqual([]);
});

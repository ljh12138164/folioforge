import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../out/', import.meta.url));
async function list(relative) {
  const entries = await readdir(root + relative, { withFileTypes: true });
  const files = await Promise.all(entries.map(entry => entry.isDirectory() ? list(`${relative}${entry.name}/`) : [`${relative}${entry.name}`]));
  return files.flat();
}
const files = [...(await list('_next/static/')).filter(path => /\.(js|css)$/.test(path)), ...await list('pdf-assets/'), 'pdf/index.html'];
const hash = createHash('sha256');
for (const path of files.sort()) { hash.update(path); hash.update(await readFile(root + path)); }
const version = hash.digest('hex').slice(0, 16);
const urls = files.filter(path => path !== 'pdf/index.html').map(path => '/' + path);
urls.push('/pdf/');
// Root scope also covers dedicated workers emitted under /_next/static/.
await writeFile(root + 'pdf-sw.js', `// Generated by build-pdf-offline.mjs. Application assets only; never user files.
const CACHE = 'pixelforge-pdf-${version}';
const ASSETS = ${JSON.stringify(urls)};
self.addEventListener('install', event => {
  event.waitUntil((async () => {
    try { await (await caches.open(CACHE)).addAll(ASSETS); }
    catch (error) { await caches.delete(CACHE); throw error; }
    await self.skipWaiting();
  })());
});
self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter(key => key.startsWith('pixelforge-pdf-') && key !== CACHE).map(key => caches.delete(key)));
    await self.clients.claim();
  })());
});
self.addEventListener('fetch', event => {
  if (event.request.method !== 'GET') return;
  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin) return;
  if (event.request.mode === 'navigate' && (url.pathname === '/pdf/' || url.pathname === '/pdf')) {
    // Fetch current HTML online; keep the versioned copy for offline navigation.
    event.respondWith((async () => {
      const cached = await (await caches.open(CACHE)).match('/pdf/');
      try {
        const response = await fetch(event.request, { cache: 'no-store' });
        return response.ok ? response : cached || response;
      } catch (error) {
        if (cached) return cached;
        throw error;
      }
    })());
    return;
  }
  if (!ASSETS.includes(url.pathname) || url.search) return;
  event.respondWith(caches.open(CACHE).then(cache => cache.match(event.request)).then(cached => cached || fetch(event.request)));
});
`);
console.log(`PDF offline cache generated: ${urls.length} assets (${version}).`);
